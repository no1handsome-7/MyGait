def load_pickle(path: Path) -> Any:
    with open(path, "rb") as f:
        return pickle.load(f)


def find_first(seq_dir: Path, names: List[str]) -> Optional[Path]:
    for name in names:
        p = seq_dir / name
        if p.exists():
            return p
    return None


def unwrap_array(obj: Any) -> np.ndarray:
    """
    Accept plain ndarray or common dict wrappers.
    """
    if isinstance(obj, np.ndarray):
        return obj

    if isinstance(obj, dict):
        for key in ["data", "array", "gpf", "gpfpp", "sils", "phase", "parts", "quality"]:
            if key in obj and isinstance(obj[key], np.ndarray):
                return obj[key]
        # Fallback: first ndarray value.
        for v in obj.values():
            if isinstance(v, np.ndarray):
                return v

    raise TypeError(f"Cannot unwrap ndarray from object type: {type(obj)}")


def ensure_tchw(x: np.ndarray, expected_channels: Optional[int] = None) -> np.ndarray:
    """
    Convert possible layouts to [T, C, H, W].

    Supported:
      [T, C, H, W]
      [T, H, W, C]
      [C, T, H, W]
      [T, H, W] -> [T, 1, H, W]
    """
    x = np.asarray(x)
    if x.ndim == 3:
        return x[:, None, :, :]

    if x.ndim != 4:
        raise ValueError(f"Expected 3D/4D array, got shape {x.shape}")

    if expected_channels is not None:
        if x.shape[1] == expected_channels:
            return x
        if x.shape[-1] == expected_channels:
            return np.transpose(x, (0, 3, 1, 2))
        if x.shape[0] == expected_channels:
            return np.transpose(x, (1, 0, 2, 3))

    # Heuristic
    if x.shape[1] <= 64 and x.shape[2] <= 256 and x.shape[3] <= 256:
        return x
    if x.shape[-1] <= 64:
        return np.transpose(x, (0, 3, 1, 2))
    if x.shape[0] <= 64:
        return np.transpose(x, (1, 0, 2, 3))
    return x


def parse_frame_index(frame_arg: str, t_len: int) -> int:
    if frame_arg.lower() == "mid":
        return max(0, t_len // 2)
    if frame_arg.lower() == "first":
        return 0
    if frame_arg.lower() == "last":
        return max(0, t_len - 1)
    idx = int(frame_arg)
    if idx < 0:
        idx = t_len + idx
    return int(np.clip(idx, 0, max(0, t_len - 1)))


def robust_limits(img: np.ndarray, symmetric: bool = False) -> Tuple[float, float]:
    arr = np.asarray(img, dtype=np.float32)
    finite = arr[np.isfinite(arr)]
    if finite.size == 0:
        return 0.0, 1.0

    lo = float(np.percentile(finite, 1))
    hi = float(np.percentile(finite, 99))

    if abs(hi - lo) < 1e-6:
        lo = float(finite.min())
        hi = float(finite.max())
        if abs(hi - lo) < 1e-6:
            hi = lo + 1.0

    if symmetric:
        m = max(abs(lo), abs(hi), 1e-6)
        return -m, m
    return lo, hi


def imshow_channel(ax, img: np.ndarray, title: str, symmetric: bool = False) -> None:
    vmin, vmax = robust_limits(img, symmetric=symmetric)
    ax.imshow(img, vmin=vmin, vmax=vmax)
    ax.set_title(title, fontsize=8)
    ax.axis("off")


def save_channel_panel(
    gpf: np.ndarray,
    frame_idx: int,
    out_path: Path,
    indices: Optional[List[int]] = None,
    title: str = "GPF++ channels",
) -> None:
    c_num = gpf.shape[1]
    if indices is None:
        indices = list(range(c_num))

    n = len(indices)
    cols = 4
    rows = int(np.ceil(n / cols))
    fig, axes = plt.subplots(rows, cols, figsize=(cols * 3.2, rows * 3.0))
    axes = np.asarray(axes).reshape(-1)

    for ax_i, ch in enumerate(indices):
        ax = axes[ax_i]
        if ch >= c_num:
            ax.axis("off")
            continue
        name = GPFPP_CHANNELS[ch] if ch < len(GPFPP_CHANNELS) else f"{ch:02d}_channel"
        symmetric = ch in [2, 3, 4, 5, 10, 11, 13, 14, 16, 20, 21, 24, 26, 27]
        imshow_channel(ax, gpf[frame_idx, ch], name, symmetric=symmetric)

    for ax in axes[n:]:
        ax.axis("off")

    fig.suptitle(f"{title} | frame={frame_idx}", fontsize=12)
    fig.tight_layout()
    fig.savefig(out_path, dpi=180)
    plt.close(fig)


def save_all_group_panels(gpf: np.ndarray, frame_idx: int, out_dir: Path) -> None:
    save_channel_panel(
        gpf, frame_idx, out_dir / f"frame_{frame_idx:04d}_all_28_channels.png",
        indices=list(range(gpf.shape[1])),
        title="GPF++ Core-28 all channels",
    )
    for group_name, idxs in GROUPS.items():
        valid = [i for i in idxs if i < gpf.shape[1]]
        if valid:
            save_channel_panel(
                gpf, frame_idx, out_dir / f"frame_{frame_idx:04d}_{group_name}.png",
                indices=valid,
                title=f"GPF++ {group_name}",
            )


def save_parts_panel(parts: Optional[np.ndarray], frame_idx: int, out_path: Path) -> None:
    if parts is None:
        return
    parts = ensure_tchw(parts)
    k = parts.shape[1]
    cols = min(6, max(1, k))
    rows = int(np.ceil(k / cols))
    fig, axes = plt.subplots(rows, cols, figsize=(cols * 3.0, rows * 2.8))
    axes = np.asarray(axes).reshape(-1)
    for i in range(k):
        imshow_channel(axes[i], parts[frame_idx, i], f"part_{i}", symmetric=False)
    for ax in axes[k:]:
        ax.axis("off")
    fig.suptitle(f"Part maps | frame={frame_idx}", fontsize=12)
    fig.tight_layout()
    fig.savefig(out_path, dpi=180)
    plt.close(fig)


def save_phase_plot(phase: Optional[np.ndarray], out_path: Path) -> None:
    if phase is None:
        return
    phase = np.asarray(phase)
    if phase.ndim != 2 or phase.shape[0] == 0:
        return

    t = np.arange(phase.shape[0])
    fig, ax = plt.subplots(figsize=(10, 4))
    labels = ["sin_phi", "cos_phi", "cycle_id", "phase_quality", "period"]
    for i in range(min(phase.shape[1], 5)):
        ax.plot(t, phase[:, i], label=labels[i] if i < len(labels) else f"phase_{i}")
    ax.set_xlabel("Frame index")
    ax.set_ylabel("Value")
    ax.set_title("Phase / cycle metadata")
    ax.legend(loc="best", fontsize=8)
    fig.tight_layout()
    fig.savefig(out_path, dpi=180)
    plt.close(fig)


def save_quality_plot(quality_obj: Optional[Any], out_dir: Path) -> None:
    if quality_obj is None:
        return

    # Supports:
    #   dict with frame-level arrays
    #   ndarray [T, Q]
    try:
        if isinstance(quality_obj, dict):
            frame_items = {}
            for k, v in quality_obj.items():
                arr = np.asarray(v)
                if arr.ndim == 1 and arr.size > 1 and np.issubdtype(arr.dtype, np.number):
                    frame_items[k] = arr.astype(np.float32)
                elif arr.ndim == 2 and arr.shape[0] > 1 and np.issubdtype(arr.dtype, np.number):
                    for j in range(arr.shape[1]):
                        frame_items[f"{k}_{j}"] = arr[:, j].astype(np.float32)

            if not frame_items:
                # Save readable JSON for sequence-level scalar metadata.
                simple = {}
                for k, v in quality_obj.items():
                    if isinstance(v, (int, float, str, bool)):
                        simple[k] = v
                    else:
                        arr = np.asarray(v)
                        if arr.size == 1:
                            simple[k] = float(arr.reshape(-1)[0])
                if simple:
                    with open(out_dir / "quality_summary.json", "w", encoding="utf-8") as f:
                        json.dump(simple, f, ensure_ascii=False, indent=2)
                return

            fig, ax = plt.subplots(figsize=(10, 4))
            t = None
            for k, arr in frame_items.items():
                if t is None:
                    t = np.arange(arr.shape[0])
                ax.plot(t, arr, label=k)
            ax.set_xlabel("Frame index")
            ax.set_ylabel("Quality value")
            ax.set_title("Frame-level quality metadata")
            ax.legend(loc="best", fontsize=8)
            fig.tight_layout()
            fig.savefig(out_dir / "quality_curves.png", dpi=180)
            plt.close(fig)
            return

        q = unwrap_array(quality_obj)
        q = np.asarray(q)
        if q.ndim == 1:
            q = q[:, None]
        if q.ndim == 2:
            fig, ax = plt.subplots(figsize=(10, 4))
            t = np.arange(q.shape[0])
            for i in range(q.shape[1]):
                ax.plot(t, q[:, i], label=f"quality_{i}")
            ax.set_xlabel("Frame index")
            ax.set_ylabel("Quality value")
            ax.set_title("Quality metadata")
            ax.legend(loc="best", fontsize=8)
            fig.tight_layout()
            fig.savefig(out_dir / "quality_curves.png", dpi=180)
            plt.close(fig)
    except Exception as e:
        with open(out_dir / "quality_visualization_error.txt", "w", encoding="utf-8") as f:
            f.write(str(e))


def save_vector_quiver(
    gpf: np.ndarray,
    frame_idx: int,
    out_path: Path,
    x_ch: int,
    y_ch: int,
    title: str,
    stride: int = 3,
) -> None:
    if x_ch >= gpf.shape[1] or y_ch >= gpf.shape[1]:
        return

    dx = gpf[frame_idx, x_ch].astype(np.float32)
    dy = gpf[frame_idx, y_ch].astype(np.float32)
    h, w = dx.shape
    yy, xx = np.mgrid[0:h:stride, 0:w:stride]
    u = dx[::stride, ::stride]
    v = dy[::stride, ::stride]

    fig, ax = plt.subplots(figsize=(5, 8))
    mag = np.sqrt(dx * dx + dy * dy)
    imshow_channel(ax, mag, title, symmetric=False)
    ax.quiver(xx, yy, u, v, angles="xy", scale_units="xy", scale=1)
    ax.set_title(f"{title} | frame={frame_idx}", fontsize=10)
    ax.axis("off")
    fig.tight_layout()
    fig.savefig(out_path, dpi=180)
    plt.close(fig)


def save_sequence_strip(
    gpf: np.ndarray,
    out_path: Path,
    channels: List[int],
    num_frames: int,
) -> None:
    t_len, c_num, _, _ = gpf.shape
    frames = np.linspace(0, max(0, t_len - 1), min(num_frames, t_len)).round().astype(int)
    channels = [ch for ch in channels if ch < c_num]

    rows = len(channels)
    cols = len(frames)
    if rows == 0 or cols == 0:
        return

    fig, axes = plt.subplots(rows, cols, figsize=(cols * 1.8, rows * 1.8))
    axes = np.asarray(axes)
    if rows == 1:
        axes = axes[None, :]
    if cols == 1:
        axes = axes[:, None]

    for r, ch in enumerate(channels):
        name = GPFPP_CHANNELS[ch] if ch < len(GPFPP_CHANNELS) else f"{ch:02d}"
        symmetric = ch in [2, 3, 4, 5, 10, 11, 13, 14, 16, 20, 21, 24, 26, 27]
        for c, fidx in enumerate(frames):
            ax = axes[r, c]
            imshow_channel(ax, gpf[fidx, ch], "", symmetric=symmetric)
            if r == 0:
                ax.set_title(f"t={fidx}", fontsize=7)
            if c == 0:
                ax.text(
                    -0.05, 0.5, name,
                    transform=ax.transAxes,
                    rotation=90,
                    va="center",
                    ha="right",
                    fontsize=7,
                )

    fig.suptitle("GPF++ sequence strip", fontsize=12)
    fig.tight_layout()
    fig.savefig(out_path, dpi=180)
    plt.close(fig)


def save_channel_stats_csv(gpf: np.ndarray, out_path: Path) -> None:
    with open(out_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["channel", "name", "min", "p01", "mean", "std", "p99", "max", "nan_count"])
        for ch in range(gpf.shape[1]):
            arr = gpf[:, ch].astype(np.float32).reshape(-1)
            finite = arr[np.isfinite(arr)]
            name = GPFPP_CHANNELS[ch] if ch < len(GPFPP_CHANNELS) else f"{ch:02d}_channel"
            if finite.size == 0:
                writer.writerow([ch, name, "", "", "", "", "", "", int(arr.size)])
                continue
            writer.writerow([
                ch,
                name,
                float(finite.min()),
                float(np.percentile(finite, 1)),
                float(finite.mean()),
                float(finite.std()),
                float(np.percentile(finite, 99)),
                float(finite.max()),
                int(np.isnan(arr).sum()),
            ])


def save_gif(gpf: np.ndarray, out_path: Path, channels: List[int], max_frames: int = 80, fps: int = 8) -> None:
    try:
        from PIL import Image
    except ImportError:
        print("[WARN] PIL/Pillow not installed. Skip GIF.")
        return

    t_len = gpf.shape[0]
    if t_len == 0:
        return

    frames_idx = np.linspace(0, t_len - 1, min(max_frames, t_len)).round().astype(int)
    channels = [ch for ch in channels if ch < gpf.shape[1]]
    if not channels:
        return

    pil_frames = []
    for fidx in frames_idx:
        cols = len(channels)
        fig, axes = plt.subplots(1, cols, figsize=(cols * 2.2, 2.6))
        axes = np.asarray(axes).reshape(-1)
        for ax, ch in zip(axes, channels):
            name = GPFPP_CHANNELS[ch] if ch < len(GPFPP_CHANNELS) else f"{ch:02d}"
            symmetric = ch in [2, 3, 4, 5, 10, 11, 13, 14, 16, 20, 21, 24, 26, 27]
            imshow_channel(ax, gpf[fidx, ch], name, symmetric=symmetric)
        fig.suptitle(f"GPF++ frame {fidx}", fontsize=10)
        fig.tight_layout()

        fig.canvas.draw()
        buf = np.asarray(fig.canvas.buffer_rgba())
        img = Image.fromarray(buf[..., :3].copy())
        pil_frames.append(img)
        plt.close(fig)

    duration_ms = int(round(1000.0 / max(1, fps)))
    pil_frames[0].save(
        out_path,
        save_all=True,
        append_images=pil_frames[1:],
        duration=duration_ms,
        loop=0,
    )


def load_optional(seq_dir: Path, names: List[str]) -> Tuple[Optional[Any], Optional[Path]]:
    p = find_first(seq_dir, names)
    if p is None:
        return None, None
    try:
        return load_pickle(p), p
    except Exception as e:
        print(f"[WARN] Failed to load {p}: {e}")
        return None, p


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seq_dir", required=True, type=str, help="Directory containing 000-gpfpp.pkl / 000-gpf.pkl.")
    parser.add_argument("--out_dir", required=True, type=str, help="Output visualization directory.")
    parser.add_argument("--frame", default="mid", type=str, help="mid, first, last, or integer frame index.")
    parser.add_argument("--num_strip_frames", default=12, type=int)
    parser.add_argument("--make_gif", action="store_true")
    parser.add_argument("--gif_fps", default=8, type=int)
    parser.add_argument("--gif_max_frames", default=80, type=int)
    parser.add_argument("--stats_csv", action="store_true")
    parser.add_argument("--quiver_stride", default=3, type=int)
    args = parser.parse_args()

    seq_dir = Path(args.seq_dir)
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    gpf_path = find_first(seq_dir, ["000-gpfpp.pkl", "000-gpf.pkl", "gpfpp.pkl", "gpf.pkl"])
    if gpf_path is None:
        raise FileNotFoundError(
            f"Cannot find GPF++ pkl in {seq_dir}. Expected one of: "
            "000-gpfpp.pkl, 000-gpf.pkl, gpfpp.pkl, gpf.pkl"
        )

    gpf_obj = load_pickle(gpf_path)
    gpf = unwrap_array(gpf_obj)
    gpf = ensure_tchw(gpf, expected_channels=28).astype(np.float32)

    if gpf.shape[1] != 28:
        print(f"[WARN] Expected 28 GPF++ channels, got shape {gpf.shape}. Script will still visualize available channels.")

    frame_idx = parse_frame_index(args.frame, gpf.shape[0])

    sil_obj, sil_path = load_optional(seq_dir, ["001-sils.pkl", "001-sil.pkl", "sils.pkl", "sil.pkl"])
    phase_obj, phase_path = load_optional(seq_dir, ["002-phase.pkl", "phase.pkl"])
    parts_obj, parts_path = load_optional(seq_dir, ["003-parts.pkl", "parts.pkl"])
    quality_obj, quality_path = load_optional(seq_dir, ["004-quality.pkl", "quality.pkl"])

    sil = None
    if sil_obj is not None:
        try:
            sil = ensure_tchw(unwrap_array(sil_obj), expected_channels=1)
        except Exception as e:
            print(f"[WARN] Failed to parse silhouette: {e}")

    phase = None
    if phase_obj is not None:
        try:
            phase = unwrap_array(phase_obj)
        except Exception:
            if isinstance(phase_obj, np.ndarray):
                phase = phase_obj
            else:
                print("[WARN] Failed to parse phase pkl.")

    parts = None
    if parts_obj is not None:
        try:
            parts = ensure_tchw(unwrap_array(parts_obj))
        except Exception as e:
            print(f"[WARN] Failed to parse parts: {e}")

    # Save metadata
    meta = {
        "seq_dir": str(seq_dir),
        "gpf_path": str(gpf_path),
        "gpf_shape_tchw": list(gpf.shape),
        "selected_frame": int(frame_idx),
        "sil_path": str(sil_path) if sil_path else None,
        "phase_path": str(phase_path) if phase_path else None,
        "parts_path": str(parts_path) if parts_path else None,
        "quality_path": str(quality_path) if quality_path else None,
    }
    with open(out_dir / "visualization_meta.json", "w", encoding="utf-8") as f:
        json.dump(meta, f, ensure_ascii=False, indent=2)

    # Main panels
    save_all_group_panels(gpf, frame_idx, out_dir)
    save_sequence_strip(
        gpf,
        out_dir / "sequence_strip_key_channels.png",
        channels=KEY_CHANNELS_FOR_STRIP,
        num_frames=args.num_strip_frames,
    )

    # Optional pkl visualizations
    if sil is not None:
        save_channel_panel(
            sil.astype(np.float32),
            frame_idx,
            out_dir / f"frame_{frame_idx:04d}_silhouette.png",
            indices=[0],
            title="Silhouette",
        )

    if parts is not None:
        save_parts_panel(parts.astype(np.float32), frame_idx, out_dir / f"frame_{frame_idx:04d}_part_maps.png")

    if phase is not None:
        save_phase_plot(np.asarray(phase), out_dir / "phase_cycle_curve.png")

    if quality_obj is not None:
        save_quality_plot(quality_obj, out_dir)

    # Vector fields
    save_vector_quiver(
        gpf, frame_idx,
        out_dir / f"frame_{frame_idx:04d}_relative_flow_quiver.png",
        x_ch=10,
        y_ch=11,
        title="Relative flow field",
        stride=args.quiver_stride,
    )
    save_vector_quiver(
        gpf, frame_idx,
        out_dir / f"frame_{frame_idx:04d}_affinity_displacement_quiver.png",
        x_ch=26,
        y_ch=27,
        title="Affinity displacement field",
        stride=args.quiver_stride,
    )

    if args.stats_csv:
        save_channel_stats_csv(gpf, out_dir / "gpfpp_channel_stats.csv")

    if args.make_gif:
        save_gif(
            gpf,
            out_dir / "gpfpp_preview.gif",
            channels=[0, 12, 15, 18, 19, 22, 24, 25],
            max_frames=args.gif_max_frames,
            fps=args.gif_fps,
        )

    print(f"[OK] GPF++ visualization saved to: {out_dir}")
    print(f"[OK] Loaded {gpf_path.name}, shape [T,C,H,W] = {gpf.shape}")
    print(f"[OK] Selected frame: {frame_idx}")


if __name__ == "__main__":
    main()
