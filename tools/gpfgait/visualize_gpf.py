#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Visualize GPF data generated by datasets/pretreatment_gpf.py.

Expected sequence folder:
    seq_dir/
        000-gpf.pkl    : [T, 12, H, W]
        001-sils.pkl   : [T, 1, H, W]
        002-phase.pkl  : [T, 2]
        003-parts.pkl  : [T, K, H, W]

Example:
    python tools/visualize_gpf.py \
        --seq_dir /path/to/CCPG-GPF-pkl/000/BG/000 \
        --out_dir ./gpf_vis/000_BG_000 \
        --frame mid \
        --make_gif
"""

import argparse
import math
import pickle
from pathlib import Path
from typing import Optional, Sequence, Tuple

import cv2
import matplotlib.pyplot as plt
import numpy as np


GPF_NAMES = [
    "00 silhouette mask",
    "01 body edge",
    "02 contour normal x",
    "03 contour normal y",
    "04 signed distance field",
    "05 motion amplitude",
    "06 phase sin map",
    "07 phase cos map",
    "08 optical-flow dx",
    "09 optical-flow dy",
    "10 motion reliability",
    "11 mid-frequency residual",
]


def load_pkl(path: Path):
    with open(path, "rb") as f:
        return pickle.load(f)


def to_numpy(x) -> np.ndarray:
    if hasattr(x, "detach"):
        x = x.detach().cpu().numpy()
    return np.asarray(x)


def find_file(seq_dir: Path, suffix: str) -> Optional[Path]:
    candidates = sorted(seq_dir.glob(f"*{suffix}"))
    return candidates[0] if candidates else None


def normalize_for_show(x: np.ndarray, mode: str = "auto") -> np.ndarray:
    """Return float image in [0, 1] for visualization."""
    x = np.asarray(x, dtype=np.float32)
    if x.size == 0:
        return x

    if mode == "zero_one":
        y = np.clip(x, 0.0, 1.0)
    elif mode == "minus_one_one":
        y = (np.clip(x, -1.0, 1.0) + 1.0) / 2.0
    elif mode == "signed_robust":
        m = np.nanpercentile(np.abs(x), 99)
        m = max(float(m), 1e-6)
        y = np.clip(x / m, -1.0, 1.0)
        y = (y + 1.0) / 2.0
    else:
        lo, hi = np.nanpercentile(x, [1, 99])
        if hi <= lo:
            hi = float(np.nanmax(x))
            lo = float(np.nanmin(x))
        if hi <= lo:
            return np.zeros_like(x, dtype=np.float32)
        y = (x - lo) / (hi - lo)
        y = np.clip(y, 0.0, 1.0)

    y = np.nan_to_num(y, nan=0.0, posinf=1.0, neginf=0.0)
    return y.astype(np.float32)


def channel_mode(channel_idx: int) -> str:
    # Channels defined in pretreatment_gpf.py:
    # [0,1,5,10] in [0,1], [2,3,4,6,7,8,9,11] in [-1,1] or signed.
    if channel_idx in [0, 1, 5, 10]:
        return "zero_one"
    if channel_idx in [2, 3, 4, 6, 7, 8, 9, 11]:
        return "minus_one_one"
    return "auto"


def resolve_frame(frame_arg: str, t: int) -> int:
    if frame_arg.lower() == "mid":
        return max(0, t // 2)
    if frame_arg.lower() == "first":
        return 0
    if frame_arg.lower() == "last":
        return max(0, t - 1)
    idx = int(frame_arg)
    return max(0, min(t - 1, idx))


def save_channel_grid(gpf: np.ndarray, out_path: Path, frame_idx: int) -> None:
    t, c, h, w = gpf.shape
    cols = 4
    rows = math.ceil(c / cols)
    fig, axes = plt.subplots(rows, cols, figsize=(cols * 3.2, rows * 3.2))
    axes = np.asarray(axes).reshape(-1)

    for ch in range(rows * cols):
        ax = axes[ch]
        ax.axis("off")
        if ch >= c:
            continue
        img = normalize_for_show(gpf[frame_idx, ch], channel_mode(ch))
        ax.imshow(img, cmap="gray", vmin=0, vmax=1)
        name = GPF_NAMES[ch] if ch < len(GPF_NAMES) else f"channel {ch:02d}"
        ax.set_title(name, fontsize=9)

    fig.suptitle(f"GPF channels | frame={frame_idx}/{t-1} | shape={gpf.shape}", fontsize=12)
    fig.tight_layout()
    fig.savefig(out_path, dpi=180)
    plt.close(fig)


def save_parts_grid(parts: Optional[np.ndarray], out_path: Path, frame_idx: int) -> None:
    if parts is None:
        return
    t, k, h, w = parts.shape
    cols = min(4, k)
    rows = math.ceil(k / cols)
    fig, axes = plt.subplots(rows, cols, figsize=(cols * 3.0, rows * 3.0))
    axes = np.asarray(axes).reshape(-1)

    for i in range(rows * cols):
        ax = axes[i]
        ax.axis("off")
        if i >= k:
            continue
        img = normalize_for_show(parts[frame_idx, i], "zero_one")
        ax.imshow(img, cmap="gray", vmin=0, vmax=1)
        ax.set_title(f"part {i}", fontsize=9)

    fig.suptitle(f"Part maps | frame={frame_idx}/{t-1} | shape={parts.shape}", fontsize=12)
    fig.tight_layout()
    fig.savefig(out_path, dpi=180)
    plt.close(fig)


def save_phase_plot(phase: Optional[np.ndarray], out_path: Path) -> None:
    if phase is None:
        return
    phase = np.asarray(phase, dtype=np.float32)
    if phase.ndim != 2 or phase.shape[1] < 2:
        return

    t = phase.shape[0]
    x = np.arange(t)
    angle = np.unwrap(np.arctan2(phase[:, 0], phase[:, 1]))

    fig = plt.figure(figsize=(10, 4.5))
    plt.plot(x, phase[:, 0], label="sin(phase)")
    plt.plot(x, phase[:, 1], label="cos(phase)")
    plt.plot(x, angle / np.pi, label="unwrapped phase / pi", linestyle="--")
    plt.xlabel("Frame index")
    plt.ylabel("Value")
    plt.title(f"Estimated gait phase | shape={phase.shape}")
    plt.legend()
    plt.grid(True, alpha=0.3)
    fig.tight_layout()
    fig.savefig(out_path, dpi=180)
    plt.close(fig)


def save_flow_quiver(gpf: np.ndarray, out_path: Path, frame_idx: int, step: int = 4) -> None:
    if gpf.shape[1] <= 10:
        return
    dx = np.asarray(gpf[frame_idx, 8], dtype=np.float32)
    dy = np.asarray(gpf[frame_idx, 9], dtype=np.float32)
    mask = normalize_for_show(gpf[frame_idx, 0], "zero_one")
    mag = np.sqrt(dx * dx + dy * dy)
    h, w = dx.shape

    yy, xx = np.mgrid[0:h:step, 0:w:step]
    u = dx[::step, ::step]
    v = -dy[::step, ::step]  # invert y for image coordinates

    fig = plt.figure(figsize=(4, 7))
    plt.imshow(mask, cmap="gray", vmin=0, vmax=1)
    plt.quiver(xx, yy, u, v, mag[::step, ::step], angles="xy", scale_units="xy", scale=0.35, width=0.006)
    plt.title(f"Optical flow field | frame={frame_idx}")
    plt.axis("off")
    fig.tight_layout()
    fig.savefig(out_path, dpi=180)
    plt.close(fig)


def save_sequence_strip(gpf: np.ndarray, out_path: Path, max_frames: int = 16) -> None:
    t = gpf.shape[0]
    idxs = np.linspace(0, t - 1, num=min(max_frames, t), dtype=int)

    show_channels = [
        (0, "mask"),
        (1, "edge"),
        (5, "motion amp"),
        (10, "motion rel."),
        (11, "mid residual"),
    ]
    cols = len(idxs)
    rows = len(show_channels)
    fig, axes = plt.subplots(rows, cols, figsize=(cols * 1.35, rows * 1.8))

    if rows == 1:
        axes = axes[None, :]
    if cols == 1:
        axes = axes[:, None]

    for r, (ch, name) in enumerate(show_channels):
        for c, idx in enumerate(idxs):
            ax = axes[r, c]
            ax.axis("off")
            img = normalize_for_show(gpf[idx, ch], channel_mode(ch))
            ax.imshow(img, cmap="gray", vmin=0, vmax=1)
            if r == 0:
                ax.set_title(str(idx), fontsize=8)
            if c == 0:
                ax.set_ylabel(name, fontsize=9)

    fig.suptitle("GPF sequence strip: columns are frame indices", fontsize=12)
    fig.tight_layout()
    fig.savefig(out_path, dpi=180)
    plt.close(fig)


def stack_panel_image(gpf_frame: np.ndarray, parts_frame: Optional[np.ndarray] = None) -> np.ndarray:
    """Create a compact RGB panel for GIF: mask, edge, motion, flow mag, residual, optional part-sum."""
    panels = []
    labels = []

    for ch, label in [(0, "mask"), (1, "edge"), (5, "motion"), (10, "reliab"), (11, "residual")]:
        img = normalize_for_show(gpf_frame[ch], channel_mode(ch))
        panels.append((img * 255).astype(np.uint8))
        labels.append(label)

    if parts_frame is not None:
        part_sum = np.clip(parts_frame.sum(axis=0), 0, 1)
        panels.append((normalize_for_show(part_sum, "zero_one") * 255).astype(np.uint8))
        labels.append("parts")

    # Resize panels for readability.
    panel_h, panel_w = 192, 96
    rendered = []
    for img, label in zip(panels, labels):
        im = cv2.resize(img, (panel_w, panel_h), interpolation=cv2.INTER_NEAREST)
        im = cv2.cvtColor(im, cv2.COLOR_GRAY2BGR)
        cv2.putText(im, label, (4, 16), cv2.FONT_HERSHEY_SIMPLEX, 0.42, (255, 255, 255), 1, cv2.LINE_AA)
        rendered.append(im)

    return np.concatenate(rendered, axis=1)


def save_gif(gpf: np.ndarray, parts: Optional[np.ndarray], out_path: Path, fps: int = 8, max_frames: int = 80) -> None:
    import imageio.v2 as imageio

    t = gpf.shape[0]
    idxs = np.linspace(0, t - 1, num=min(t, max_frames), dtype=int)
    frames = []
    for idx in idxs:
        pf = parts[idx] if parts is not None else None
        panel = stack_panel_image(gpf[idx], pf)
        cv2.putText(panel, f"frame {idx}", (4, panel.shape[0] - 8), cv2.FONT_HERSHEY_SIMPLEX, 0.45, (255, 255, 255), 1, cv2.LINE_AA)
        frames.append(cv2.cvtColor(panel, cv2.COLOR_BGR2RGB))

    duration = 1.0 / max(1, fps)
    imageio.mimsave(str(out_path), frames, duration=duration)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seq_dir", type=str, required=True, help="Folder containing 000-gpf.pkl etc.")
    parser.add_argument("--out_dir", type=str, required=True, help="Folder to save visualization images.")
    parser.add_argument("--frame", type=str, default="mid", help="'first', 'mid', 'last', or an integer frame index.")
    parser.add_argument("--make_gif", action="store_true", help="Also save an animated GIF.")
    parser.add_argument("--fps", type=int, default=8)
    parser.add_argument("--max_gif_frames", type=int, default=80)
    parser.add_argument("--strip_frames", type=int, default=16)
    args = parser.parse_args()

    seq_dir = Path(args.seq_dir)
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    gpf_path = find_file(seq_dir, "-gpf.pkl")
    sil_path = find_file(seq_dir, "-sils.pkl")
    phase_path = find_file(seq_dir, "-phase.pkl")
    parts_path = find_file(seq_dir, "-parts.pkl")

    if gpf_path is None:
        raise FileNotFoundError(f"No *-gpf.pkl found in {seq_dir}")

    gpf = to_numpy(load_pkl(gpf_path))
    if gpf.ndim != 4:
        raise ValueError(f"Expected GPF shape [T,C,H,W], got {gpf.shape}")

    sil = to_numpy(load_pkl(sil_path)) if sil_path else None
    phase = to_numpy(load_pkl(phase_path)) if phase_path else None
    parts = to_numpy(load_pkl(parts_path)) if parts_path else None

    frame_idx = resolve_frame(args.frame, gpf.shape[0])

    print(f"[INFO] seq_dir: {seq_dir}")
    print(f"[INFO] gpf:   {gpf.shape} {gpf.dtype} from {gpf_path.name}")
    if sil is not None:
        print(f"[INFO] sil:   {sil.shape} {sil.dtype} from {sil_path.name}")
    if phase is not None:
        print(f"[INFO] phase: {phase.shape} {phase.dtype} from {phase_path.name}")
    if parts is not None:
        print(f"[INFO] parts: {parts.shape} {parts.dtype} from {parts_path.name}")
    print(f"[INFO] visualizing frame: {frame_idx}")

    save_channel_grid(gpf, out_dir / f"frame_{frame_idx:04d}_gpf_channels.png", frame_idx)
    save_parts_grid(parts, out_dir / f"frame_{frame_idx:04d}_part_maps.png", frame_idx)
    save_phase_plot(phase, out_dir / "phase_curve.png")
    save_flow_quiver(gpf, out_dir / f"frame_{frame_idx:04d}_flow_quiver.png", frame_idx)
    save_sequence_strip(gpf, out_dir / "sequence_strip.png", max_frames=args.strip_frames)

    if args.make_gif:
        save_gif(gpf, parts, out_dir / "gpf_preview.gif", fps=args.fps, max_frames=args.max_gif_frames)

    print(f"[DONE] Saved visualizations to: {out_dir}")


if __name__ == "__main__":
    main()
